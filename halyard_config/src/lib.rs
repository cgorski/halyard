fn env_wo_default(key: &str) -> Result<Option<String>, HalyardConfigError> {
    match std::env::var(key) {
        Ok(val) => Ok(Some(val)),
        Err(VarError::NotPresent) => Ok(None),
        Err(e) => Err(HalyardConfigError::EnvVarError(format!("{key}: {e}"))),
    }
}
#[cfg_attr(not(test), allow(dead_code))]
fn env_w_default(
    key: &str,
    default: &str,
) -> Result<String, HalyardConfigError> {
    match std::env::var(key) {
        Ok(val) => Ok(val),
        Err(VarError::NotPresent) => Ok(default.to_string()),
        Err(e) => Err(HalyardConfigError::EnvVarError(format!("{key}: {e}"))),
    }
}

pub const ENV_DEV_KEY_SHORT: &str = "dev";
pub const ENV_DEV_KEY_LONG: &str = "development";
pub const ENV_PROD_KEY_SHORT: &str = "prod";
pub const ENV_PROD_KEY_LONG: &str = "production";

/// An enum that can be used to define the environment Halyard is running in.
/// Setting this to the `PROD` variant will not include the WebSocket code for `cargo-halyard` watch mode.
/// Defaults to `DEV`.
#[derive(Debug, Clone, serde::Serialize, PartialEq, Eq, Default)]
pub enum Env {
    PROD,
    #[default]
    DEV,
}

fn env_from_str(input: &str) -> Result<Env, HalyardConfigError> {
    let sanitized = input.to_lowercase();
    match sanitized.as_ref() {
        ENV_DEV_KEY_SHORT | ENV_DEV_KEY_LONG => Ok(Env::DEV),
        ENV_PROD_KEY_SHORT | ENV_PROD_KEY_LONG => Ok(Env::PROD),
        _ => Err(HalyardConfigError::InvalidEnv {
            value: input.to_string(),
        }),
    }
}

impl FromStr for Env {
    type Err = ();
    fn from_str(input: &str) -> Result<Self, Self::Err> {
        env_from_str(input).or_else(|_| Ok(Self::default()))
    }
}

/// Parses `dev`, `development`, `prod` or `production`, in any case.
impl TryFrom<&str> for Env {
    type Error = HalyardConfigError;

    fn try_from(str: &str) -> Result<Self, Self::Error> {
        env_from_str(str)
    }
}

/// Parses the result of `std::env::var("HALYARD_ENV")`: an unset (or unreadable)
/// variable is the default, [`Env::DEV`].
impl TryFrom<&Result<String, VarError>> for Env {
    type Error = HalyardConfigError;

    fn try_from(input: &Result<String, VarError>) -> Result<Self, Self::Error> {
        match input {
            Ok(str) => env_from_str(str),
            Err(_) => Ok(Self::default()),
        }
    }
}

impl TryFrom<String> for Env {
    type Error = HalyardConfigError;

    fn try_from(s: String) -> Result<Self, Self::Error> {
        env_from_str(s.as_str())
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Hash)]
struct EnvVisitor;

impl<'de> serde::de::Visitor<'de> for EnvVisitor {
    type Value = Env;

    fn expecting(
        &self,
        formatter: &mut std::fmt::Formatter,
    ) -> std::fmt::Result {
        write!(
            formatter,
            "a case-insensitive string of either `{ENV_DEV_KEY_SHORT}`, \
             `{ENV_DEV_KEY_LONG}`, `{ENV_PROD_KEY_SHORT}`, or \
             `{ENV_PROD_KEY_LONG}`"
        )
    }

    fn visit_str<E>(self, v: &str) -> Result<Self::Value, E>
    where
        E: serde::de::Error,
    {
        env_from_str(v).map_err(|err| E::custom(err.to_string()))
    }
}

impl<'de> serde::Deserialize<'de> for Env {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        deserializer.deserialize_any(EnvVisitor)
    }
}

/// An enum that can be used to define the websocket protocol Halyard uses for live reloading
