/// Finds the first line of `text` that starts with `prefix`, and returns how many lines
/// come before it, and the text from its start to the end.
fn find_line_starting_with<'a>(
    text: &'a str,
    prefix: &str,
) -> Option<(usize, &'a str)> {
    let mut rest = text;
    let mut lines_before = 0_usize;
    loop {
        if rest.starts_with(prefix) {
            return Some((lines_before, rest));
        }
        (_, rest) = rest.split_once('\n')?;
        // one line per newline, so it cannot pass `text.len()`
        lines_before = lines_before.checked_add(1)?;
    }
}

/// Loads [`HalyardOptions`] from a Cargo.toml text content with layered overrides.
/// If an env var is specified, like `HALYARD_ENV` (or the legacy `LEPTOS_ENV`),
/// it will override a setting in the file.
///
/// The settings are read from a `[package.metadata.halyard]` or
/// `[[workspace.metadata.halyard]]` section; the legacy `[package.metadata.leptos]`
/// / `[[workspace.metadata.leptos]]` section names are accepted as a fallback
/// so that existing `cargo-leptos` projects keep working.
///
/// # Errors
///
/// This function will return an error if either:
/// - config section was not found;
/// - failed to deserialize the config section.
pub fn get_config_from_str(
    text: &str,
) -> Result<HalyardOptions, HalyardConfigError> {
    let (metadata_name, (newlines, section_text)) = [
        "[package.metadata.halyard]",
        "[[workspace.metadata.halyard]]",
        // legacy section names
        "[package.metadata.leptos]",
        "[[workspace.metadata.leptos]]",
    ]
    .iter()
    .find_map(|section| {
        find_line_starting_with(text, section).map(|found| (section, found))
    })
    .ok_or(HalyardConfigError::ConfigSectionNotFound)?;

    // so that serde error messages have right line number
    let input = "\n".repeat(newlines) + section_text;
    // so the settings will be interpreted as root level settings
    let toml = input.replace(metadata_name, "");
    let settings = Config::builder()
        // Read the "default" configuration file
        .add_source(File::from_str(&toml, FileFormat::Toml))
        // Layer on the environment-specific values.
        // Legacy `LEPTOS_*` variables first, then `HALYARD_*` so the latter win.
        // E.g. `HALYARD_RELOAD_PORT=5001 would set `HalyardOptions.reload_port`
        .add_source(
            config::Environment::with_prefix(LEGACY_ENV_PREFIX)
                .convert_case(Case::Kebab),
        )
        .add_source(
            config::Environment::with_prefix(ENV_PREFIX)
                .convert_case(Case::Kebab),
        )
        .build()?;

    settings
        .try_deserialize()
        .map_err(|e| HalyardConfigError::ConfigError(e.to_string()))
}

/// Loads [`HalyardOptions`] from a Cargo.toml with layered overrides. If an env var is specified, like `HALYARD_ENV`,
/// it will override a setting in the file. It takes in an optional path to a Cargo.toml file. If None is provided,
/// you'll need to set the options as environment variables or rely on the defaults. This is the preferred
/// approach for cargo-halyard. If Some("./Cargo.toml") is provided, Halyard will read in the settings itself. This
/// option currently does not allow dashes in file or folder names, as all dashes become underscores
///
/// # Errors
///
/// See [`get_config_from_file`] & [`get_config_from_env`]
pub fn get_configuration(
    path: Option<&str>,
) -> Result<ConfFile, HalyardConfigError> {
    if let Some(path) = path {
        get_config_from_file(path)
    } else {
        get_config_from_env()
    }
}

/// Loads [`HalyardOptions`] from a `Cargo.toml` with layered overrides.
/// Halyard will read in the settings itself.
///
/// This option currently does not allow dashes in file or folder names, as all dashes become underscores.
///
/// # Errors
///
/// This function will return an error if either:
/// - path was not found, or other I/O error has occurred;
/// - [`get_config_from_str`] returned an error.
pub fn get_config_from_file<P: AsRef<Path>>(
    path: P,
) -> Result<ConfFile, HalyardConfigError> {
    let text = fs::read_to_string(path)
        .map_err(|_| HalyardConfigError::ConfigNotFound)?;
    let halyard_options = get_config_from_str(&text)?;
    Ok(ConfFile { halyard_options })
}

/// Loads [`HalyardOptions`] from environment variables or rely on the defaults.
///
/// # Errors
///
/// This function will return an error if it failed to load or parse a relevant environment variable.
pub fn get_config_from_env() -> Result<ConfFile, HalyardConfigError> {
    Ok(ConfFile {
        halyard_options: HalyardOptions::try_from_env()?,
    })
}

